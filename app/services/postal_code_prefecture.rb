  # @param postal_code [String, nil] ハイフンなし7桁の郵便番号
  # @return [Integer, nil] 都道府県コード(1〜47)。判定できない場合はnil
  def self.code_for(postal_code)
    return nil if postal_code.blank?

    digits = postal_code.to_s.gsub(/\D/, '')
    return nil unless digits.length == 7

    zip = digits.to_i
    RANGES_BY_PREFECTURE_CODE.each do |code, ranges|
      return code if ranges.any? { |range| range.cover?(zip) }
    end
    nil
  end
